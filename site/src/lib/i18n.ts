// Tout le texte de l'interface, dans les deux langues. `en` est typé sur `fr` : une clé oubliée
// casse `npm run typecheck`.
export type Lang = "fr" | "en";

export const langPaths = () => [{ params: { lang: undefined } }, { params: { lang: "en" } }];
export const langOf = (param: string | undefined): Lang => (param === "en" ? "en" : "fr");
export const href = (lang: Lang, path: string) => (lang === "fr" ? path : `/en${path}`);
export const day = (lang: Lang, iso: string) =>
  new Date(iso).toLocaleDateString(lang === "fr" ? "fr-FR" : "en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });

